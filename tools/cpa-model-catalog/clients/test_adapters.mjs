assert.deepEqual(v2.providers['cpa-chat'].models['devin/swe-2'].variants.map(x=>x.id),['medium','high','max']);
assert.deepEqual(v2.providers['cpa-chat'].models['devin/swe-2'].variants[2].body,{reasoning_effort:'max'});
assert.deepEqual(v2.providers['cpa-codex'].models['gpt-6-astra'].cost[1].tier,{type:'context',size:272000});
console.log('OpenCode v2 adapter checks passed.');
